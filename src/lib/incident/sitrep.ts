import type { IncidentState } from "./types";

/** Build a D4H-style Situation Report (SITREP) from live incident data. */
export function buildSitrep(state: IncidentState): string {
  const { situation } = state;
  const op =
    [...state.operationalPeriods].sort((a, b) => b.number - a.number)[0] ?? null;
  const taskItems = state.taskLists.flatMap((l) => l.items);
  const tasksOpen = taskItems.filter((t) => t.status !== "complete" && t.status !== "canceled");
  const tasksDone = taskItems.filter((t) => t.status === "complete").length;
  const recentLogs = state.logs.slice(0, 8);

  const lines: string[] = [
    "SITUATION REPORT (SITREP)",
    "========================",
    "",
    `Incident: ${situation.name}`,
    `Activation: ${situation.activationLevel.toUpperCase()}`,
    `Report time: ${new Date().toISOString()}`,
    "",
    "--- CURRENT SITUATION ---",
    situation.summary || "(No summary recorded — update in Situation module.)",
    "",
    "--- LOCATION ---",
    situation.location || "(No address)",
    situation.lat != null && situation.lng != null
      ? `Coordinates: ${situation.lat.toFixed(5)}, ${situation.lng.toFixed(5)}`
      : "",
    "",
    "--- OBJECTIVES ---",
    situation.objectives || "(No objectives recorded.)",
    "",
  ];

  if (op) {
    lines.push(
      "--- OPERATIONAL PERIOD ---",
      `${op.name} (OP ${op.number})`,
      `Period: ${op.startsAt} → ${op.endsAt || "open"}`,
      op.objectives || "",
      "",
    );
  }

  lines.push(
    "--- KEY CONTACTS ---",
    situation.keyContacts || "(None listed.)",
    "",
    "--- OPERATIONAL METRICS ---",
    `Personnel: ${state.personnel.length} (${state.personnel.filter((p) => p.online).length} online)`,
    `Open tasks: ${tasksOpen.length} | Complete: ${tasksDone}`,
    `Resource requests: ${state.resourceRequests.length}`,
    `Shelters: ${state.shelters.length} | Residents tracked: ${state.residents.length}`,
    `Road impacts: ${state.roadDamages.length}`,
    `Damage assessments: ${state.damages.length}`,
    `Map overlays: ${state.mapAnnotations.length}`,
    `ICS forms: ${state.forms.length}`,
    "",
    "--- RECENT LOG ENTRIES ---",
  );

  if (recentLogs.length === 0) {
    lines.push("(No log entries yet.)");
  } else {
    for (const log of recentLogs) {
      lines.push(`[${log.createdAt}] ${log.author}: ${log.message}`);
    }
  }

  lines.push("", "--- END SITREP ---", "Generated by InCommand Mitiga");
  return lines.filter(Boolean).join("\n");
}
